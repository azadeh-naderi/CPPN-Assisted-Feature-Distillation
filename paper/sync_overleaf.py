"""Two-way sync between paper/ and the Overleaf project, over Overleaf's git
integration, with each file owned by one side so neither overwrites edits:

- repo -> Overleaf: figures/*.pdf and tables/*.tex (generated by
  make_figures.py, or hand-compiled in the repo)
- Overleaf -> repo: main.tex and references.bib (the prose is written in
  Overleaf)

    python paper/sync_overleaf.py            # sync, push generated files to Overleaf
    python paper/sync_overleaf.py --dry-run  # show what would change

The Overleaf project is cloned once into ../overleaf-cppn-paper (next to the
repo); git credentials for git.overleaf.com come from your credential
manager. Prose pulled into the repo is left for you to review and commit.
"""

import argparse
import filecmp
import shutil
import subprocess
from pathlib import Path

PAPER = Path(__file__).resolve().parent
REPO_ROOT = PAPER.parent
OVERLEAF_URL = "https://git.overleaf.com/6ae3c586083ac000744a067d"
DEFAULT_CLONE = REPO_ROOT.parent / "overleaf-cppn-paper"

TO_OVERLEAF = ["figures/*.pdf", "tables/*.tex"]
FROM_OVERLEAF = ["main.tex", "references.bib"]


def git(clone: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(clone), *args], check=True, capture_output=True, text=True).stdout


TEXT_SUFFIXES = {".tex", ".bib", ".md"}


def changed(src: Path, dst: Path) -> bool:
    """Content differs. Text files are compared ignoring line endings: a
    Windows checkout of the repo has CRLF, Overleaf stores LF."""
    if not dst.exists():
        return True
    if src.suffix in TEXT_SUFFIXES:
        return src.read_bytes().replace(b"\r\n", b"\n") != dst.read_bytes().replace(b"\r\n", b"\n")
    return not filecmp.cmp(src, dst, shallow=False)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--clone", default=str(DEFAULT_CLONE))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    clone = Path(args.clone)

    if not (clone / ".git").exists():
        subprocess.run(["git", "clone", OVERLEAF_URL, str(clone)], check=True)
    git(clone, "pull", "--ff-only")

    pushed = []
    for pattern in TO_OVERLEAF:
        for src in sorted(PAPER.glob(pattern)):
            dst = clone / src.relative_to(PAPER)
            if changed(src, dst):
                pushed.append(src.relative_to(PAPER).as_posix())
                if not args.dry_run:
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dst)

    pulled = []
    for name in FROM_OVERLEAF:
        src, dst = clone / name, PAPER / name
        if src.exists() and changed(src, dst):
            pulled.append(name)
            if not args.dry_run:
                shutil.copy2(src, dst)

    prefix = "would push" if args.dry_run else "pushed"
    print(f"{prefix} to Overleaf: {', '.join(pushed) or 'nothing'}")
    print(f"{'would pull' if args.dry_run else 'pulled'} from Overleaf: {', '.join(pulled) or 'nothing'}")
    if pushed and not args.dry_run:
        git(clone, "add", *pushed)
        git(clone, "-c", "user.name=sync_overleaf.py", "-c", "user.email=noreply@localhost", "commit", "-q", "-m",
            f"Sync generated files from the repo: {', '.join(pushed)}")
        git(clone, "push", "-q")
    if pulled and not args.dry_run:
        print("review the pulled prose with `git diff paper/` and commit it in the repo")


if __name__ == "__main__":
    main()
